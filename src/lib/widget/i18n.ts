export type WidgetLocale = (typeof WIDGET_LOCALES)[number]["code"];

export const DEFAULT_LOCALE: WidgetLocale = "nl";

export function isWidgetLocale(v: unknown): v is WidgetLocale {
  return (
    typeof v === "string" &&
    WIDGET_LOCALES.some((l) => l.code === v)
  );
}

export function normalizeLocale(v: unknown): WidgetLocale {
  return isWidgetLocale(v) ? v : DEFAULT_LOCALE;
}

const DATE_FNS: Record<WidgetLocale, DateFnsLocale> = {
  nl,
  en: enGB,
  fr,
  de,
  es,
  it,
  ru,
  uk,
  pl,
  tr,
};

export function dateFnsLocale(locale: WidgetLocale): DateFnsLocale {
  return DATE_FNS[locale] ?? nl;
}

