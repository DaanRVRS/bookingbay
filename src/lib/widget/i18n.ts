const DICTS: Record<WidgetLocale, Dict> = {
  nl: NL,
  en: EN,
  fr: FR,
  de: DE,
  es: ES,
  it: IT,
  ru: RU,
  uk: UK,
  pl: PL,
  tr: TR,
};

export type Translator = (
  key: TKey,
  vars?: Record<string, string | number>,
) => string;

export function makeT(locale: WidgetLocale): Translator {
  const dict = DICTS[locale] ?? NL;
  return (key, vars) => {
    let s = dict[key] ?? NL[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
      }
    }
    return s;
  };
}
